import { chromium } from '/usr/lib/node_modules/openclaw/node_modules/playwright-core/index.mjs';
import fs from 'fs';
const base='https://supercitadel.62.146.238.213.sslip.io';
const raw=fs.readFileSync('/tmp/seed.txt','utf8').trim();
const login=await fetch(base+'/api/v1/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({token:raw})}).then(r=>r.json());
const b=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium-browser',args:['--no-sandbox','--disable-dev-shm-usage']});
const p=await b.newPage({viewport:{width:1365,height:900}});
await p.goto(base+'/home');
await p.evaluate((login)=>localStorage.setItem('citadel.session', JSON.stringify({jwt:login.jwt,user:login.user})),login);
await p.reload({waitUntil:'networkidle'});
await p.goto(base+'/ke-toan-10a',{waitUntil:'networkidle'});
await p.waitForTimeout(1500);
await p.evaluate(()=>window.dispatchEvent(new Event('citadel:tutorial-start')));
await p.getByRole('button',{name:/Tiếp/}).click();
await p.getByRole('button',{name:/Tiếp/}).click();
await p.getByRole('button',{name:/Quay lại/}).click();
await p.screenshot({path:'shots/r111-k10a-tour-back.png',fullPage:true});
await p.goto(base+'/tieu-tam',{waitUntil:'networkidle'});
await p.screenshot({path:'shots/r111-tieu-tam-paperclip.png',fullPage:true});
await b.close();
